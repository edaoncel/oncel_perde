    <h3 style="text-align: center; color: #000;">KVKK AYDINLATMA METNİ</h3>
    
    <p><strong>1. VERİ SORUMLUSU</strong><br>
    6698 sayılı Kişisel Verilerin Korunması Kanunu ("KVKK") uyarınca, kişisel verileriniz; veri sorumlusu sıfatıyla <strong>Öncel </strong> tarafından aşağıda açıklanan kapsamda işlenebilecektir.</p>

    <p><strong>2. KİŞİSEL VERİLERİN İŞLENME AMACI</strong><br>
    Toplanan kişisel verileriniz;
    <ul>
        <li>Ürün ve hizmetlerimizin size sunulabilmesi,</li>
        <li>Sipariş süreçlerinin yönetimi, teslimatın gerçekleştirilmesi ve müşteri desteği sağlanması,</li>
        <li>Yasal mevzuattan kaynaklanan yükümlülüklerin yerine getirilmesi,</li>
        <li>Kampanya ve avantajlardan haberdar edilmeniz,</li>
        amaçlarıyla KVKK'nın 5. ve 6. maddelerinde belirtilen kişisel veri işleme şartları dahilinde işlenmektedir.</li>
    </ul>
    </p>

    <p><strong>3. KİŞİSEL VERİLERİN AKTARILMASI</strong><br>
    Kişisel verileriniz; yukarıda belirtilen amaçların gerçekleştirilmesi doğrultusunda, iş ortaklarımıza, lojistik/kargo firmalarına, ödeme altyapısı sağlayıcılarımıza ve kanunen yetkili kamu kurumlarına aktarılabilecektir.</p>

    <p><strong>4. KİŞİSEL VERİ TOPLAMA YÖNTEMİ VE HUKUKİ SEBEBİ</strong><br>
    Kişisel verileriniz, internet sitemiz üzerinden yapmış olduğunuz işlemler vasıtasıyla elektronik ortamda toplanmaktadır. Hukuki sebep, sözleşmenin ifası ve kanuni yükümlülüklerimizin yerine getirilmesidir.</p>

    <p><strong>5. KVKK KAPSAMINDAKİ HAKLARINIZ</strong><br>
    KVKK'nın 11. maddesi uyarınca veri sahibi olarak; kişisel verilerinizin işlenip işlenmediğini öğrenme, işlenmişse buna ilişkin bilgi talep etme, verilerin işlenme amacını ve bunların amacına uygun kullanılıp kullanılmadığını öğrenme ve verilerin düzeltilmesini talep etme haklarına sahipsiniz.</p>

    <p><em>Öncel olarak kişisel verilerinizin güvenliğine en üst düzeyde önem veriyoruz.</em></p>
